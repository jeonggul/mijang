/*
 * BatchStatus — 배치가 어떻게 끝났는가
 *
 * 이 파일이 하는 일
 *   배치 한 번의 결과를 나타내는 값의 목록이다.
 *   성공·실패 말고 "건너뜀"이 따로 있는 것이 중요하다 — 휴장일이라 안 돈 것과
 *   터져서 못 돈 것은 완전히 다른 일인데, 둘을 같게 적으면 관리자가
 *   멀쩡한 날을 장애로 오해한다.
 */
package com.example.mijang.admin.domain;

/**
 * 배치 실행 결과. 스키마의 ENUM 과 값이 같아야 한다.
 *
 * <p>{@code SKIPPED} 가 따로 있는 것이 중요하다 — 휴장일이라 안 돈 것과
 * 실패해서 못 돈 것은 다르다(2.4).
 */
public enum BatchStatus {
    /** 정상 완료. */
    SUCCESS,
    /** 일부만 처리. 묶음 중 몇 개가 실패한 경우다. */
    PARTIAL,
    /** 실패. */
    FAILED,
    /** 돌 필요가 없어 건너뜀. 휴장일·주말 등. */
    SKIPPED
}
